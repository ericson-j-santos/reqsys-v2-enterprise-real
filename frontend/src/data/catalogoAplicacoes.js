export function filtrarCatalogoAplicacoes(itens, termo = '') {
  const busca = String(termo ?? '').trim().toLocaleLowerCase('pt-BR')
  if (!busca) return itens
  return itens.filter(item => [item.id, item.nome, item.tipo, item.caminho, item.repositorio]
    .some(valor => String(valor ?? '').toLocaleLowerCase('pt-BR').includes(busca)))
}
